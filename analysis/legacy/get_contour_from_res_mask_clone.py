"""
TL;DR
-----
This script converts tracked resistant clone mask stacks into contour stacks.
It keeps clone identities on boundary pixels so downstream visualization can
show clone outlines rather than filled clone regions.

Detailed
--------
Inputs:
- `clone_masks_stacks/*.tif` generated by clone tracking.

Outputs:
- `clone_contour_stacks/*_contours.tif` files for each processed sample.

How it works:
- Iterates over all clone-mask stacks in the selected plates.
- Processes each frame independently, filling holes inside each clone first so
  contours represent the outer clone extent rather than internal mask gaps.
- Uses boundary extraction and writes the clone label onto contour pixels.

Pipeline role:
- Geometry-conversion helper between clone tracking and clone-oriented plotting
  or visual inspection.
"""

import os
import numpy as np
import tifffile
from scipy.ndimage import binary_fill_holes
from skimage.segmentation import find_boundaries

# ==============================================================================
#                         USER PARAMETERS
# ==============================================================================

# Base directory containing Plate_1, Plate_4, Plate_5, Plate_6
BASE_DIR = r"D:\2025_08_CoreSeed_Large_Testdataset"

# List all the plate‐folders you want to process. Adjust as needed.
PLATE_NAMES = ["Plate_1", "Plate_2", "Plate_3", "Plate_4", "Plate_5", "Plate_6" ,"Plate_7", "Plate_8"]

# Subfolder names relative to each plate:
CLONE_MASKS_SUBFOLDER     = "clone_masks_stacks"
CONTOUR_OUTPUT_SUBFOLDER  = "clone_contour_stacks"

# ==============================================================================
#                         CONTOUR‐EXTRACTION LOOP
# ==============================================================================

for plate in PLATE_NAMES:
    plate_dir = os.path.join(BASE_DIR, plate)
    if not os.path.isdir(plate_dir):
        print(f"[Warning] Plate folder not found, skipping: {plate_dir}")
        continue

    # Input folder: where your clone‐mask TIFFs live (plus some CSVs you want to ignore)
    masks_folder = os.path.join(plate_dir, CLONE_MASKS_SUBFOLDER)
    if not os.path.isdir(masks_folder):
        print(f"[Warning] clone_masks_stacks not found under {plate_dir}, skipping.")
        continue

    # Output folder: where to write the new “clone‐contours” TIFFs
    output_folder = os.path.join(plate_dir, CONTOUR_OUTPUT_SUBFOLDER)
    os.makedirs(output_folder, exist_ok=True)

    print(f"\n=== Processing {plate} ===")
    print(f"Reading masks from:   {masks_folder}")
    print(f"Writing contours to:  {output_folder}\n")

    # Iterate over every file in clone_masks_stacks/
    for filename in os.listdir(masks_folder):
        # Skip anything that isn’t a TIFF (e.g. CSV files)
        if not filename.lower().endswith((".tif", ".tiff")):
            continue

        print(f"  • Found mask‐stack: {filename}")
        input_path = os.path.join(masks_folder, filename)

        # Base name without extension, e.g. "B2_ATAgent-B2_res_clone_masks"
        base = os.path.splitext(filename)[0]

        # Load the 3D clone‐mask stack (T × H × W)
        mask_stack = tifffile.imread(input_path)
        if mask_stack.ndim != 3:
            print(f"    [Error] Expected a 3D TIFF but got shape {mask_stack.shape}, skipping.")
            continue
        T, H, W = mask_stack.shape

        # Prepare an empty array for the contour stack (dtype=uint8)
        contour_stack = np.zeros((T, H, W), dtype=np.uint8)

        # Process each timepoint
        for t in range(T):
            frame = mask_stack[t]

            # Start with a frame of all 1's (meaning “non‐clone interior”)
            contour_frame = np.ones((H, W), dtype=np.uint8)

            # 1) Wherever frame == 0 (background), mark contour_frame=0
            contour_frame[frame == 0] = 0

            # 2) Find all clone labels ≥ 2 present in this frame
            unique_labels = np.unique(frame)
            clone_labels = [int(L) for L in unique_labels if L >= 2]

            # For each clone‐label L, fill holes and extract boundary
            for L in clone_labels:
                clone_mask = (frame == L)

                # Fill holes inside that clone’s region
                filled = binary_fill_holes(clone_mask)

                # Extract the outer boundary of every connected island in ‘filled’
                boundary = find_boundaries(filled, mode="outer")

                # Wherever boundary == True, mark that pixel = L
                contour_frame[boundary] = L

            # Save this 2D contour_frame into the 3D stack
            contour_stack[t] = contour_frame

        # Write out the full 3D contour stack for this sample
        out_filename = f"{base}_contours.tif"
        out_path = os.path.join(output_folder, out_filename)
        tifffile.imwrite(out_path, contour_stack, imagej=True)
        print(f"    → Saved contour‐stack: {out_path}")

    print(f"=== Done with {plate} ===\n")

print("All plates processed.")
