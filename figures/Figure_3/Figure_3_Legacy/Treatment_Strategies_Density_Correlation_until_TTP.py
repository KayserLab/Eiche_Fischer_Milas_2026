def _format_tick_label(value: float) -> str:
    if np.isclose(value, round(value)):
        return f"{int(round(value))}"
    return f"{value:.2f}".rstrip("0").rstrip(".")


def _timepoint_to_day(tp: int) -> int:
    if tp < 1:
        raise ValueError(f"_timepoint_to_day expects tp >= 1, got {tp}")
    day = 1
    for k in range(2, tp + 1):
        step = 2 if ((k - 2) % 3) in (0, 1) else 3
        day += step
    return day


def _forward_rate(y: np.ndarray, t: np.ndarray) -> np.ndarray:
    dt = np.asarray(t[1:] - t[:-1], dtype=float)
    dy = np.asarray(y[1:] - y[:-1], dtype=float)
    out = np.full(dt.shape, np.nan, dtype=float)
    mask = np.isfinite(dt) & np.isfinite(dy) & (dt > 0)
    out[mask] = dy[mask] / dt[mask]
    return out


def _manual_cutoff_day(sample: str) -> float:
    rule = experiment_filters.EXCLUDE_SAMPLES.get(str(sample), "KEEP")
    if rule is None:
        return np.nan
    if rule == "KEEP":
        return np.nan
    try:
        return float(rule)
    except (TypeError, ValueError):
        return np.nan


def _is_fully_excluded(sample: str) -> bool:
    return experiment_filters.EXCLUDE_SAMPLES.get(str(sample), "KEEP") is None


def _results_path(plate: str, sample: str) -> Path | None:
    results_dir = DATASET_ROOT / str(plate) / RESULTS_DIR_NAME
    if not results_dir.is_dir():
        return None

    matches = []
    for path in results_dir.glob(f"Results_*_{sample}.txt"):
        name = path.name.lower()
        if "overexposed" in name or "seg" in name:
            continue
        matches.append(path)
    if not matches:
        return None
    return sorted(matches)[0]


def _load_results_table(path: Path) -> pd.DataFrame:
    data = pd.read_csv(
        path,
        sep=r"\s+",
        header=None,
        names=["DayRaw", "Green", "Red"],
    )
    if data.empty:
        return data

    day_raw = data["DayRaw"].astype(str)
    merged_mask = day_raw.str.contains("MTDr", na=False) | day_raw.str.contains("ncr", na=False)
    data["Green"] = pd.to_numeric(data["Green"], errors="coerce")
    data["Red"] = pd.to_numeric(data["Red"], errors="coerce")
    data.loc[merged_mask, "Red"] = data.loc[merged_mask, "Red"] + data.loc[merged_mask, "Green"]
    data.loc[merged_mask, "Green"] = 0

    day_match = day_raw.str.extract(r"d(\d+)$")
    data["day"] = pd.to_numeric(day_match[0], errors="coerce")
    data = data.dropna(subset=["day"]).copy()
    if data.empty:
        return data

    data["day"] = data["day"].astype(int)
    data["Total"] = pd.to_numeric(data["Green"], errors="coerce") + pd.to_numeric(data["Red"], errors="coerce")
    return data.sort_values("day").reset_index(drop=True)


def _build_well_censoring_table(samples: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict] = []
    for rec in samples.sort_values(["strategy", "plate", "sample"]).itertuples(index=False):
        plate = str(rec.plate)
        sample = str(rec.sample)
        strategy = normalize_strategy(str(rec.strategy))
        manual_cutoff = _manual_cutoff_day(sample)

        row = {
            "strategy": strategy,
            "plate": plate,
            "sample": sample,
            "manual_cutoff_day": manual_cutoff,
            "ttp_day": np.nan,
            "event": 0,
            "censor_day": manual_cutoff,
            "censor_reason": "manual_cutoff" if np.isfinite(manual_cutoff) else "none",
            "status": "usable",
            "baseline_total": np.nan,
        }

        if _is_fully_excluded(sample):
            row["status"] = "fully_excluded"
            row["censor_reason"] = "fully_excluded"
            rows.append(row)
            continue

        path = _results_path(plate, sample)
        if path is None:
            row["status"] = "missing_results"
            rows.append(row)
            continue

        try:
            results = _load_results_table(path)
        except Exception as exc:
            row["status"] = f"results_error: {exc}"
            rows.append(row)
            continue

        if results.empty:
            row["status"] = "empty_results"
            rows.append(row)
            continue

        norm_idx = 1 if ("Dens" in sample and len(results) > 1) else 0
        baseline_total = float(results["Total"].iloc[norm_idx])
        row["baseline_total"] = baseline_total
        if baseline_total <= 0 or not np.isfinite(baseline_total):
            row["status"] = "invalid_baseline"
            rows.append(row)
            continue

        res_norm = pd.to_numeric(results["Red"], errors="coerce") / baseline_total
        hit_days = results.loc[res_norm >= RES_NORM_THRESHOLD, "day"]
        if not hit_days.empty:
            ttp_day = float(hit_days.iloc[0])
            row["ttp_day"] = ttp_day
            row["event"] = 1
            if not np.isfinite(row["censor_day"]) or ttp_day < float(row["censor_day"]):
                row["censor_day"] = ttp_day
                row["censor_reason"] = "ttp"
            elif np.isclose(ttp_day, float(row["censor_day"])):
                row["censor_reason"] = "ttp_and_manual_cutoff"

        rows.append(row)

    return pd.DataFrame(rows)


def _load_density_by_replicate_timepoint() -> pd.DataFrame:
    if not ALL_TREATMENT_DENSITY_CSV.is_file():
        raise FileNotFoundError(
            "All-treatment density-correlation CSV not found. Run "
            "analysis/Density_Experiments_Density_Correlation_analysis_CT.py first: "
            f"{ALL_TREATMENT_DENSITY_CSV}"
        )

    df = pd.read_csv(ALL_TREATMENT_DENSITY_CSV)
    required = {"plate", "sample", "strategy", "clone_label", "timepoint", DENSITY_COL}
    missing = sorted(required - set(df.columns))
    if missing:
        raise ValueError(f"All-treatment density-correlation CSV missing columns: {missing}")

    work = pd.DataFrame(
        {
            "plate": df["plate"].astype(str),
            "sample": df["sample"].astype(str),
            "strategy_raw": df["strategy"].astype(str),
            "clone_label": pd.to_numeric(df["clone_label"], errors="coerce"),
            "timepoint": pd.to_numeric(df["timepoint"], errors="coerce"),
            "x_density": (
                pd.to_numeric(df[DENSITY_COL], errors="coerce")
                / DENSITY_SCALE_FACTOR
                * DENSITY_DISPLAY_SCALE
            ),
        }
    )
    work["strategy"] = work["strategy_raw"].map(normalize_strategy)

    if "day" in df.columns:
        work["day"] = pd.to_numeric(df["day"], errors="coerce")
    else:
        work["day"] = np.nan

    work = work.dropna(subset=["clone_label", "timepoint", "x_density"]).copy()
    work["clone_label"] = work["clone_label"].astype(int)
    work["timepoint"] = work["timepoint"].astype(int)

    missing_day = ~np.isfinite(work["day"])
    if missing_day.any():
        work.loc[missing_day, "day"] = work.loc[missing_day, "timepoint"].map(_timepoint_to_day)
    work["day"] = work["day"].astype(float)

    density = (
        work.groupby(["strategy", "plate", "sample", "timepoint", "day"], as_index=False, dropna=False)
        .agg(
            x_density=("x_density", "median"),
            n_density_rows=("x_density", "size"),
            n_density_clones=("clone_label", "nunique"),
        )
        .sort_values(["strategy", "plate", "sample", "timepoint"])
        .reset_index(drop=True)
    )
    return density


def _clone_counts_path(plate: str, sample: str) -> Path:
    return DATASET_ROOT / str(plate) / CLONE_COUNTS_DIR_NAME / f"{sample}_clone_counts_raw.csv"


def _load_count_growth_rates(well_censoring: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict] = []
    missing_files: list[str] = []

    usable = well_censoring[well_censoring["status"] != "fully_excluded"].copy()
    for rec in usable.sort_values(["strategy", "plate", "sample"]).itertuples(index=False):
        plate = str(rec.plate)
        sample = str(rec.sample)
        strategy = normalize_strategy(str(rec.strategy))
        path = _clone_counts_path(plate, sample)
        if not path.is_file():
            missing_files.append(f"{plate}/{sample}")
            continue

        try:
            counts = pd.read_csv(path)
        except Exception as exc:
            print(f"[WARN] Could not read clone counts for {plate}/{sample}: {exc}")
            continue

        clone_cols = [col for col in counts.columns if str(col).startswith("clone_")]
        if not clone_cols:
            print(f"[WARN] No clone_* columns in {path}")
            continue

        counts[clone_cols] = counts[clone_cols].apply(pd.to_numeric, errors="coerce")
        resistant = counts[clone_cols].sum(axis=1, min_count=1).to_numpy(dtype=float)
        if resistant.size < 2:
            continue

        timepoints = np.arange(1, resistant.size + 1, dtype=int)
        days = np.asarray([_timepoint_to_day(int(tp)) for tp in timepoints], dtype=float)
        growth_abs = _forward_rate(resistant, days)
        growth_rel = np.full_like(growth_abs, np.nan, dtype=float)
        mask = np.isfinite(growth_abs) & np.isfinite(resistant[:-1]) & (resistant[:-1] > 0)
        growth_rel[mask] = growth_abs[mask] / resistant[:-1][mask]

        censor_day = float(rec.censor_day) if np.isfinite(rec.censor_day) else np.nan
        ttp_day = float(rec.ttp_day) if np.isfinite(rec.ttp_day) else np.nan
        event = int(rec.event)
        for i, y_value in enumerate(growth_rel):
            left_day = float(days[i])
            right_day = float(days[i + 1])
            if not np.isfinite(y_value):
                continue
            # Use complete intervals only; no interval may extend beyond the
            # earlier of manual exclusion/truncation or TTP.
            if np.isfinite(censor_day) and right_day > censor_day:
                continue
            rows.append(
                {
                    "strategy": strategy,
                    "plate": plate,
                    "sample": sample,
                    "timepoint": int(timepoints[i]),
                    "day": left_day,
                    "day_tp1": right_day,
                    "ttp_day": ttp_day,
                    "event": event,
                    "manual_cutoff_day": float(rec.manual_cutoff_day) if np.isfinite(rec.manual_cutoff_day) else np.nan,
                    "censor_day": censor_day,
                    "censor_reason": str(rec.censor_reason),
                    "resistant_count": float(resistant[i]),
                    "resistant_count_tp1": float(resistant[i + 1]),
                    "y_growth": float(y_value),
                }
            )

    if missing_files:
        print(f"[WARN] Missing clone-count CSVs for {len(missing_files)} usable replicate(s): {missing_files}")

    if not rows:
        return pd.DataFrame(
            columns=[
                "strategy",
                "plate",
                "sample",
                "timepoint",
                "day",
                "day_tp1",
                "ttp_day",
                "event",
                "manual_cutoff_day",
                "censor_day",
                "censor_reason",
                "resistant_count",
                "resistant_count_tp1",
                "y_growth",
            ]
        )
    return pd.DataFrame(rows).sort_values(["strategy", "plate", "sample", "timepoint"]).reset_index(drop=True)


def _build_points_until_ttp() -> tuple[pd.DataFrame, pd.DataFrame]:
    density = _load_density_by_replicate_timepoint()
    samples = density[["strategy", "plate", "sample"]].drop_duplicates().reset_index(drop=True)
    well_censoring = _build_well_censoring_table(samples)
    rates = _load_count_growth_rates(well_censoring)
    if rates.empty:
        raise RuntimeError("No resistant clone-count growth rates available before exclusion/TTP censoring.")

    points = density.merge(
        rates,
        on=["strategy", "plate", "sample", "timepoint", "day"],
        how="inner",
    )
    if points.empty:
        raise RuntimeError("No density rows matched clone-count growth rates after exclusion/TTP filtering.")

    return points.sort_values(["strategy", "plate", "sample", "timepoint"]).reset_index(drop=True), well_censoring


def _summarize_binned(points: pd.DataFrame, bins: np.ndarray) -> pd.DataFrame:
    if points.empty:
        return pd.DataFrame()

    work = points.copy()
    work["x_bin"] = pd.cut(work["x_density"], bins=np.asarray(bins, dtype=float), include_lowest=True, right=True)
    work = work.dropna(subset=["x_bin"]).copy()
    if work.empty:
        return pd.DataFrame()

    summary = (
        work.groupby(["strategy", "x_bin"], observed=True, as_index=False)
        .agg(
            y_center=("y_growth", "median"),
            y_q25=("y_growth", lambda values: np.nanquantile(values, 0.25)),
            y_q75=("y_growth", lambda values: np.nanquantile(values, 0.75)),
            n_points=("y_growth", "size"),
            n_replicates=("sample", "nunique"),
        )
    )
    summary["x_center"] = summary["x_bin"].apply(lambda interval: float(interval.mid))
    return summary.sort_values(["strategy", "x_center"]).reset_index(drop=True)


def _strategy_sort_key(strategy: str) -> tuple[int, str]:
    canonical = normalize_strategy(strategy)
    try:
        return STRATEGY_ORDER.index(canonical), canonical
    except ValueError:
        return len(STRATEGY_ORDER), canonical


def _plot_strategy_summary(ax: plt.Axes, summary: pd.DataFrame, strategy: str) -> None:
    sub = summary[summary["strategy"] == strategy].copy()
    if sub.empty:
        return

    x = pd.to_numeric(sub["x_center"], errors="coerce").to_numpy(dtype=float)
    y = pd.to_numeric(sub["y_center"], errors="coerce").to_numpy(dtype=float)
    q25 = pd.to_numeric(sub["y_q25"], errors="coerce").to_numpy(dtype=float)
    q75 = pd.to_numeric(sub["y_q75"], errors="coerce").to_numpy(dtype=float)
    mask = np.isfinite(x) & np.isfinite(y) & np.isfinite(q25) & np.isfinite(q75)
    if not np.any(mask):
        return

    color = get_color(strategy)
    ax.fill_between(x[mask], q25[mask], q75[mask], color=color, alpha=0.35, zorder=1)
    ax.plot(x[mask], y[mask], "o-", color=color, linewidth=1.2, markersize=3.2, zorder=2)


def _plot(points: pd.DataFrame, summary: pd.DataFrame, well_censoring: pd.DataFrame) -> None:
    strategies = sorted(summary["strategy"].dropna().unique(), key=_strategy_sort_key)
    if not strategies:
        raise RuntimeError("No strategies available for plotting.")

    ncols = min(3, len(strategies))
    nrows = int(math.ceil(len(strategies) / ncols))
    fig, axes = ft.new_subplots(
        nrows=nrows,
        ncols=ncols,
        ax_width_mm=FIGURE_AXES_WIDTH_MM,
        ax_height_mm=FIGURE_AXES_HEIGHT_MM,
        margins=FIGURE_MARGINS_MM,
        wspace_mm=FIGURE_PANEL_GAP_MM,
        hspace_mm=FIGURE_PANEL_GAP_MM,
        sharex=True,
        sharey=True,
        squeeze=False,
        dpi=DPI,
        apply_style=False,
    )
    axes_arr = np.asarray(axes).ravel()

    usable_wells = well_censoring[well_censoring["status"] != "fully_excluded"].copy()
    usable_counts = usable_wells.groupby("strategy")["sample"].nunique().to_dict()
    point_counts = points.groupby("strategy")["sample"].nunique().to_dict()

    for idx, (ax, strategy) in enumerate(zip(axes_arr, strategies)):
        _plot_strategy_summary(ax, summary, strategy)
        ax.set_title(
            f"{get_display_name(strategy)}\n"
            f"n={int(point_counts.get(strategy, 0))}/{int(usable_counts.get(strategy, 0))}",
            pad=2.0,
        )
        ax.set_xlim(*X_LIM)
        ax.set_ylim(*Y_LIM)
        ax.set_xticks(X_TICKS)
        ax.set_xticklabels([_format_tick_label(float(x)) for x in X_TICKS])
        ax.grid(True, linewidth=0.5, alpha=0.25)

        row = idx // ncols
        col = idx % ncols
        if row == nrows - 1:
            ax.set_xlabel(X_AXIS_LABEL)
        else:
            ax.tick_params(axis="x", labelbottom=False)
        if col == 0:
            ax.set_ylabel(Y_AXIS_LABEL)
        else:
            ax.tick_params(axis="y", labelleft=False)

    for ax in axes_arr[len(strategies):]:
        ax.set_visible(False)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    ft.savefig(fig, OUT_BASENAME.with_suffix(".pdf"))
    ft.savefig(fig, OUT_BASENAME.with_suffix(".png"))
    plt.close(fig)


def main() -> None:
    points, well_censoring = _build_points_until_ttp()
    summary = _summarize_binned(points, BINS)
    if summary.empty:
        raise RuntimeError("Binned treatment-strategy summary is empty.")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    well_censoring.to_csv(OUT_TIMING_CSV, index=False)
    points.to_csv(OUT_POINTS_CSV, index=False)
    summary.to_csv(OUT_SUMMARY_CSV, index=False)
    _plot(points, summary, well_censoring)

    strategy_counts = points.groupby("strategy")["sample"].nunique().sort_index().to_dict()
    censor_counts = well_censoring["censor_reason"].value_counts(dropna=False).sort_index().to_dict()
    print(f"[OK] replicate-timepoint rows: {len(points)}")
    print(f"[OK] binned summary rows: {len(summary)}")
    print(f"[OK] replicate counts with plotted rows by strategy: {strategy_counts}")
    print(f"[OK] censor reasons: {censor_counts}")
    print(f"[OK] saved: {OUT_BASENAME.with_suffix('.pdf')}")
    print(f"[OK] saved: {OUT_BASENAME.with_suffix('.png')}")
    print(f"[OK] saved: {OUT_TIMING_CSV}")
    print(f"[OK] saved: {OUT_POINTS_CSV}")
    print(f"[OK] saved: {OUT_SUMMARY_CSV}")


if __name__ == "__main__":
    main()
