"""
TL;DR
-----
Build a CT-colony-style density-versus-growth summary for all treatment
strategies, using resistant clone-count growth and restricting intervals to TTP.

Detailed
--------
Inputs:
- All-treatment density-correlation CSV generated by
  `analysis/Density_Experiments_Density_Correlation_analysis_CT.py`.
- Raw `plots_clones/*_clone_counts_raw.csv` resistant clone-count tables.
- Raw `Results/*.txt` replicate trajectories for TTP detection.
- Shared manual exclusion/truncation rules from `experiment_filters.py`.

Outputs:
- A multi-panel PDF/PNG with one density-binned trajectory per treatment
  strategy.
- The replicate-timepoint points and binned summaries used for the plot.

How it works:
- Uses all wells present in the all-treatment density-correlation CSV unless
  they are fully excluded by `experiment_filters`.
- Keeps complete growth intervals until the earlier of manual cutoff or TTP.
- Collapses the density-correlation clone rows to one median local boundary
  density per replicate/timepoint, matching the old CT plotting script.
- Computes resistant growth with the same definition used by the CT branch in
  `Density_Experiment_Density_Correlation_plot_both.py`: sum all `clone_*`
  columns in `clone_counts_raw.csv`, take the forward rate, and divide by the
  left-timepoint resistant count.
"""

